#!/bin/bash

# 🚀 One-Command Setup for Ultimate Full-Stack Template
# Usage: ./setup.sh [project-name]

set -e

PROJECT_NAME=${1:-"my-awesome-app"}
echo "🚀 Setting up '$PROJECT_NAME' with the ultimate full-stack template..."

# Colors for pretty output
RED='\033[0;31m'
GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

echo -e "${BLUE}📦 Installing dependencies...${NC}"
npm install

echo -e "${BLUE}🔧 Setting up D1 database...${NC}"
if command -v wrangler &> /dev/null; then
    echo "✅ Wrangler found"
    
    # Create D1 database
    echo -e "${YELLOW}Creating D1 database '$PROJECT_NAME-db'...${NC}"
    DB_RESULT=$(wrangler d1 create "$PROJECT_NAME-db" --json 2>/dev/null || echo "skip")
    
    if [ "$DB_RESULT" != "skip" ]; then
        DATABASE_ID=$(echo "$DB_RESULT" | grep -o '"database_id":"[^"]*' | cut -d'"' -f4)
        echo -e "${GREEN}✅ D1 database created with ID: $DATABASE_ID${NC}"
        
        # Update wrangler.json with real database ID
        sed -i '' "s/placeholder-database-id-replace-with-real-id/$DATABASE_ID/g" wrangler.json
        
        # Apply schema
        echo -e "${YELLOW}Applying database schema...${NC}"
        wrangler d1 execute "$PROJECT_NAME-db" --file=./schema.sql
        echo -e "${GREEN}✅ Database schema applied${NC}"
    else
        echo -e "${YELLOW}⚠️  D1 database creation skipped (might already exist)${NC}"
    fi
else
    echo -e "${YELLOW}⚠️  Wrangler not found. Install with: npm install -g wrangler${NC}"
fi

echo -e "${BLUE}🎨 Creating example files...${NC}"

# Create an example page
cat > src/react-frontend/pages/ExamplePage.tsx << 'EOF'
import { useState, useEffect } from 'react';

export default function ExamplePage() {
  const [data, setData] = useState<any>(null);
  
  useEffect(() => {
    fetch('/api/')
      .then(res => res.json())
      .then(setData);
  }, []);

  return (
    <div className="card">
      <h1>🎉 Example Page</h1>
      <p>This page was generated by the setup script!</p>
      
      <div className="card">
        <h2>API Response:</h2>
        <pre>{JSON.stringify(data, null, 2)}</pre>
      </div>
      
      <div className="card">
        <h2>Next Steps:</h2>
        <ul style={{ textAlign: 'left' }}>
          <li>Edit this page in <code>src/react-frontend/pages/ExamplePage.tsx</code></li>
          <li>Add new routes in <code>src/react-frontend/App.tsx</code></li>
          <li>Create API endpoints in <code>src/workers-backend/routes/api/</code></li>
          <li>Check out <code>SIMPLE.md</code> for step-by-step guides</li>
        </ul>
      </div>
    </div>
  );
}
EOF

# Add to pages index
if ! grep -q "ExamplePage" src/react-frontend/pages/index.ts; then
  echo "export { default as ExamplePage } from './ExamplePage';" >> src/react-frontend/pages/index.ts
fi

# Add route to App.tsx
if ! grep -q "ExamplePage" src/react-frontend/App.tsx; then
  sed -i '' 's/import { HomePage, AboutPage } from/import { HomePage, AboutPage, ExamplePage } from/' src/react-frontend/App.tsx
  sed -i '' 's|<Route path="/about" element={<AboutPage />} />|<Route path="/about" element={<AboutPage />} />\n          <Route path="/example" element={<ExamplePage />} />|' src/react-frontend/App.tsx
fi

echo -e "${GREEN}✅ Example page created at /example${NC}"

echo -e "${BLUE}🧪 Testing the setup...${NC}"
if npm run build > /dev/null 2>&1; then
    echo -e "${GREEN}✅ Build successful${NC}"
else
    echo -e "${RED}❌ Build failed. Check the output above.${NC}"
fi

echo ""
echo -e "${GREEN}🎉 Setup complete! Your project '$PROJECT_NAME' is ready!${NC}"
echo ""
echo -e "${BLUE}🚀 Next steps:${NC}"
echo -e "  ${YELLOW}npm run dev${NC}     # Start development server"
echo -e "  ${YELLOW}npm run build${NC}   # Build for production"  
echo -e "  ${YELLOW}npm run deploy${NC}  # Deploy to Cloudflare Workers"
echo ""
echo -e "${BLUE}📖 Documentation:${NC}"
echo -e "  ${YELLOW}README.md${NC}   # Quick overview"
echo -e "  ${YELLOW}SIMPLE.md${NC}   # Step-by-step guides"
echo -e "  ${YELLOW}.CLAUDE.md${NC}  # AI agent reference"
echo ""
echo -e "${GREEN}Happy coding! 🚀${NC}"